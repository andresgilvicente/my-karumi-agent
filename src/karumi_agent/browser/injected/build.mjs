/**
 * Build the page-side bundle injected into the target site.
 *
 * Output is a single self-executing IIFE with no imports, no network fetches
 * and no globals beyond `window.__karumi`, because Playwright's
 * `addInitScript` evaluates it as a plain script at document start.
 *
 * A note on size. `@pipecat-ai/client-js` ships as a Parcel bundle whose
 * exports are registered through `$parcel$exportWildcard` — a module-scope side
 * effect that defeats tree-shaking in every bundler, esbuild included. Asking
 * for `snapshotDocument` therefore pulls in the whole SDK, including the
 * `PipecatClient` class we never instantiate.
 *
 * We accept that, because the alternative — vendoring or reimplementing the
 * walker — would give up the one property that makes this architecture work:
 * refs allocated by the *same* code the official UI Worker client uses, with
 * the same cross-snapshot stability guarantee. Inert bytes are a cheaper price
 * than a divergent fork of the observation layer.
 *
 * What we do enforce is that nothing capable of reaching the network, the
 * microphone or the camera makes it into a page we do not own. That list is
 * asserted below and verified again at runtime by
 * `tests/integration/test_injected_bundle.py`, which loads the bundle in a real
 * browser and diffs the global object.
 */

import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const outfile = join(here, "dist", "karumi-page.js");

/**
 * Capabilities that must never reach a third-party page. Unlike dead classes,
 * these are things that could actually *do* something: open a peer connection,
 * grab media, or phone home. Any hit here is a hard build failure.
 */
const FORBIDDEN = [
  "RTCPeerConnection",
  "getUserMedia",
  "getDisplayMedia",
  "new WebSocket",
  "navigator.sendBeacon",
];

const result = await build({
  entryPoints: [join(here, "src", "index.js")],
  outfile,
  bundle: true,
  format: "iife",
  target: ["chrome120"],
  platform: "browser",
  treeShaking: true,
  // Minified: this is injected at document start on every navigation and in
  // every frame, so parse time is on the critical path of the demo.
  minify: true,
  legalComments: "none",
  metafile: true,
  banner: {
    js: "/* karumi-agent page bundle — Pipecat a11y walker + Karumi overlay. Generated by build.mjs; do not edit. */",
  },
});

const code = await readFile(outfile, "utf8");
const violations = FORBIDDEN.filter((needle) => code.includes(needle));

if (violations.length > 0) {
  throw new Error(
    `Bundle contains capability-bearing code (${violations.join(", ")}). ` +
      "Nothing injected into a third-party page may open connections or " +
      "capture media; re-check the client-js exports before shipping this.",
  );
}

const bytes = Buffer.byteLength(code);
const inputs = Object.keys(result.metafile.outputs[
  Object.keys(result.metafile.outputs).find((k) => k.endsWith(".js"))
].inputs).length;

await writeFile(
  join(here, "dist", "build-report.json"),
  `${JSON.stringify({ bytes, modules: inputs, forbidden_checked: FORBIDDEN }, null, 2)}\n`,
);

console.log(
  `built ${outfile} — ${(bytes / 1024).toFixed(1)} kB from ${inputs} modules, ` +
    `no transport code present`,
);
